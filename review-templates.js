/**
 * 获取评语类型信息 - 增强版调试
 */
function getReviewTypeInfo(reviewType) {
  const info = REVIEW_TYPES[reviewType];
  if (!info) {
    return REVIEW_TYPES["progress_audit"];
  }
  return info;
}

