/**
 * 构建评语提示词
 * @param {string} reviewType    审核类型
 * @param {string} cid1Content   textarea#cid_1_widget 的内容
 * @param {string} cid3Content   textarea#cid_3_widget 的内容
 * @param {string} projectTitle  课题名称
 * @param {string} teacherText   教师评语参考
 * @param {string} userInputText 用户在评语输入框中已手动输入的内容（Ctrl+点击文本框触发时传入）
 * @param {{ min: number, max: number } | null} wordRange 评语字数范围（从页面 p.d-rightTips 动态提取）
 * @param {string} pageRequirements 页面上的硬性要求（如参考文献篇数、外文文献篇数），可选
 */
function buildPrompt(reviewType, cid1Content, cid3Content, projectTitle, teacherText, userInputText, wordRange, pageRequirements) {
  const typeInfo = getReviewTypeInfo(reviewType);

  // 直接使用原始字数范围，不再乘以 9/10 调整
  let wordRangeStr = "200-250字";
  if (wordRange && typeof wordRange.min === "number" && typeof wordRange.max === "number") {
    wordRangeStr = `${wordRange.min}-${wordRange.max}字`;
  }

  const placeholders = [
    { key: "{project_title}", value: projectTitle || "（未获取到课题名称）" },
    { key: "{cid1_content}", value: cid1Content || "（无内容）" },
    { key: "{cid3_content}", value: cid3Content || "（无内容）" },
    { key: "{teacher_text}", value: teacherText || "（无教师评语参考，请根据学生内容和课题名称给出正面评价）" },
    { key: "{user_input_text}", value: userInputText || "（用户未预先输入内容）" },
    { key: "{word_range}", value: wordRangeStr },
    {
      key: "{page_requirements}",
      value: pageRequirements ||
        "（未从页面提取到明示要求，请按常规本科毕业设计任务书规范核对：参考文献不少于10篇，外文文献不少于1-2篇；达到或超过下限均视为合格，超出不违规）",
    },
  ];

  let userPrompt = typeInfo.user_prompt_template;
  let systemPrompt = typeInfo.system_prompt;
  for (const ph of placeholders) {
    const re = new RegExp(ph.key.replace(/[{}]/g, "\\$&"), "g");
    userPrompt = userPrompt.replace(re, ph.value);
    systemPrompt = systemPrompt.replace(re, ph.value);
  }

  return {
    name: typeInfo.name,
    system_prompt: systemPrompt,
    user_prompt: userPrompt,
  };
}

