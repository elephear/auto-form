// ============================================================
// dowhat 映射函数
//
// 支持两种格式：
//   1. 结构化格式（新）：任务类-子任务-动作
//      例：工作记录-提交工作记录-审核
//          定稿-提交定稿-审核
//          定稿-最终稿-审核
//          任务书-提交任务书-新增
//
//   2. 关键词格式（旧/兼容）：直接匹配关键词
//      例："进度审核"、"定稿"、"开题"、"guidancelog"
// ============================================================
function mapDowhatToType(dowhat) {
  if (!dowhat) return "progress_audit";

  const d = dowhat.toLowerCase();

  // ============================================================
  // 结构化格式匹配（任务类-子任务-动作）
  // ============================================================
  const parts = dowhat.split("-").map(s => s.trim()).filter(s => s.length > 0);

  if (parts.length >= 2) {
    const taskCategory = parts[0];       // 任务类（Level 1）
    const subTask = parts[1];             // 子任务（Level 2）

    // --- 定稿类 ---
    // 子任务包含"最终" → 最终稿审核
    // 否则 → 定稿审核
    if (taskCategory === "定稿") {
      if (subTask.includes("最终")) {
        return "final_draft_audit";
      }
      return "final_version_audit";
    }

    // --- 课题类 ---
    // 子任务包含"开题" → 开题报告审核
    if (taskCategory === "课题") {
      if (subTask.includes("开题")) {
        return "proposal_audit";
      }
      // 课题的其他子任务暂不处理
      return "progress_audit";
    }

    // --- 任务书类 ---
    if (taskCategory === "任务书") {
      return "task_book_audit";
    }

    // --- 过程检查情况记录类 ---
    if (taskCategory === "过程检查情况记录" || taskCategory.includes("过程检查")) {
      // 检查子任务是否含"中期"
      if (subTask.includes("中期")) {
        return "midterm_audit";
      }
      return "progress_audit";
    }

    // --- 初稿类 ---
    if (taskCategory === "初稿") {
      return "first_draft_audit";
    }

    // --- 工作记录类（默认映射到进度审核）---
    if (taskCategory === "工作记录") {
      return "progress_audit";
    }

    // 其他未识别的任务类，继续用关键词匹配
  }

  // ============================================================
  // 关键词格式匹配（旧版兼容 + 兜底）
  // ============================================================
  if (d.includes("进度") || d.includes("过程检查") || d.includes("guidancelog")) {
    return "progress_audit";
  } else if (d.includes("定稿") && !d.includes("最终")) {
    return "final_version_audit";
  } else if (d.includes("最终稿")) {
    return "final_draft_audit";
  } else if (d.includes("初稿")) {
    return "first_draft_audit";
  } else if (d.includes("中期") || d.includes("中期检查")) {
    return "midterm_audit";
  } else if (d.includes("任务书")) {
    return "task_book_audit";
  } else if (d.includes("开题")) {
    return "proposal_audit";
  }
  return "progress_audit";
}

// ============================================================
// 审核对象判别（"审核什么"）
// ============================================================
// 输入：从页面/弹窗中提取到的线索文本（主页面任务类、子任务标签、
//       iframe / 文档标题、tplConfig.name、mapping 路径、弹窗标题等）
// 输出：评语类型（REVIEW_TYPES 的 key）；无法识别时返回空串

var AUDIT_TARGET_NAMES = {
  task_book_audit: "任务书",
  proposal_audit: "开题报告",
  first_draft_audit: "初稿",
  final_version_audit: "定稿",
  final_draft_audit: "最终稿",
  midterm_audit: "中期检查材料",
  progress_audit: "过程检查 / 进度材料",
};

/**
 * 依据一段文本判定审核对象所属的评语类型
 * 规则从"最具体"到"最宽泛"依次匹配
 * @param {string} text
 * @returns {string} 评语类型 key，未识别返回 ""
 */
function detectReviewTypeFromText(text) {
  if (!text) return "";
  var t = String(text);

  if (/任务书|task_?book/i.test(t)) return "task_book_audit";
  if (/开题|proposal/i.test(t)) return "proposal_audit";
  if (/中期|midterm/i.test(t)) return "midterm_audit";
  // 定稿类：子任务含"最终" → 最终稿审核
  if (/最终稿|final_?draft/i.test(t)) return "final_draft_audit";
  if (/定稿|final_?version/i.test(t)) return "final_version_audit";
  if (/初稿|first_?draft/i.test(t)) return "first_draft_audit";
  if (/过程检查|进度|工作记录|指导记录|guidance_?log/i.test(t)) return "progress_audit";
  return "";
}

/**
 * 评语类型 → 中文审核对象名称
 * @param {string} reviewType
 * @returns {string}
 */
function getAuditTargetName(reviewType) {
  return AUDIT_TARGET_NAMES[reviewType] || "毕业设计材料";
}

